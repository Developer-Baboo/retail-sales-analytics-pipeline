"""Build an Excel management report with live formulas, formatting and a chart."""
from openpyxl import Workbook
from openpyxl.chart import BarChart, LineChart, Reference
from openpyxl.formatting.rule import DataBarRule
from openpyxl.styles import Alignment, Font, PatternFill

from db import ROOT
from queries import get_reports

HDR_FILL = PatternFill("solid", start_color="1F3864")
HDR_FONT = Font(name="Arial", bold=True, color="FFFFFF")
BASE = Font(name="Arial", size=10)
MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def _write_table(ws, df, start_row=1, money_cols=(), pct_cols=()):
    for j, col in enumerate(df.columns, 1):
        c = ws.cell(row=start_row, column=j, value=col.replace("_", " ").title())
        c.fill, c.font, c.alignment = HDR_FILL, HDR_FONT, Alignment(horizontal="center")
    for i, row in enumerate(df.itertuples(index=False), start_row + 1):
        for j, v in enumerate(row, 1):
            c = ws.cell(row=i, column=j, value=v.item() if hasattr(v, "item") else v)
            c.font = BASE
            name = df.columns[j - 1]
            if name in money_cols:
                c.number_format = '#,##0;(#,##0);"-"'
            if name in pct_cols:
                c.number_format = "0.0%"
    for j in range(1, len(df.columns) + 1):
        ws.column_dimensions[ws.cell(row=1, column=j).column_letter].width = 18
    ws.freeze_panes = ws.cell(row=start_row + 1, column=1)
    return start_row + len(df)


def build(path=None):
    path = path or ROOT / "output" / "sales_report.xlsx"
    r = get_reports()
    wb = Workbook()

    # ---- Monthly sheet (with margin formula + chart)
    ws = wb.active
    ws.title = "Monthly"
    m = r["monthly"].copy()
    m["period"] = [f"{MONTHS[int(mo)-1]} {int(y)}" for y, mo in zip(m["year"], m["month"])]
    m = m[["period", "revenue", "profit", "orders"]]
    last = _write_table(ws, m, money_cols=("revenue", "profit"))
    ws["E1"], ws["E1"].fill, ws["E1"].font = "Margin %", HDR_FILL, HDR_FONT
    for i in range(2, last + 1):
        ws[f"E{i}"] = f"=IFERROR(C{i}/B{i},0)"
        ws[f"E{i}"].number_format, ws[f"E{i}"].font = "0.0%", BASE
    t = last + 1
    ws[f"A{t}"] = "Total"
    for col in "BCD":
        ws[f"{col}{t}"] = f"=SUM({col}2:{col}{last})"
        ws[f"{col}{t}"].number_format = '#,##0' 
    ws[f"E{t}"] = f"=IFERROR(C{t}/B{t},0)"
    ws[f"E{t}"].number_format = "0.0%"
    for col in "ABCDE":
        ws[f"{col}{t}"].font = Font(name="Arial", bold=True)
    ch = LineChart()
    ch.title, ch.height, ch.width = "Monthly Revenue vs Profit", 9, 22
    ch.add_data(Reference(ws, min_col=2, max_col=3, min_row=1, max_row=last), titles_from_data=True)
    ch.set_categories(Reference(ws, min_col=1, min_row=2, max_row=last))
    ch.roundedCorners = False
    ch.legend.overlay = False
    ch.title.overlay = False
    ch.x_axis.delete = False
    ch.y_axis.delete = False
    ws.add_chart(ch, "G2")

    # ---- Category / Region / Products
    for name, key, money in [("Category", "category", ("revenue", "profit", "units")),
                             ("Region", "region", ("revenue", "profit")),
                             ("Top Products", "top_products", ("revenue", "profit"))]:
        s = wb.create_sheet(name)
        df = r[key]
        n = _write_table(s, df, money_cols=money)
        pc = len(df.columns) + 1
        s.cell(row=1, column=pc, value="Margin %").fill = HDR_FILL
        s.cell(row=1, column=pc).font = HDR_FONT
        for i in range(2, n + 1):
            s.cell(row=i, column=pc, value=f"=IFERROR(C{i}/B{i},0)").number_format = "0.0%"
            s.cell(row=i, column=pc).font = BASE
        s.conditional_formatting.add(f"B2:B{n}", DataBarRule(start_type="min", end_type="max", color="5B9BD5"))
        if key != "top_products":
            bc = BarChart()
            bc.title, bc.height, bc.width = f"Revenue by {name}", 8, 14
            bc.add_data(Reference(s, min_col=2, min_row=1, max_row=n), titles_from_data=True)
            bc.set_categories(Reference(s, min_col=1, min_row=2, max_row=n))
            bc.roundedCorners = False
            bc.legend = None
            bc.title.overlay = False
            bc.x_axis.delete = False
            bc.y_axis.delete = False
            s.add_chart(bc, "H2")

    # ---- Notes
    notes = wb.create_sheet("Notes")
    for i, line in enumerate([
        "Data source: synthetic retail sales generated by src/generate_data.py (no real customer data).",
        "Numbers come from the SQL star schema (fact_sales + dimensions). Margin % cells are live formulas.",
        "Tip: for ad-hoc analysis, connect Excel to vw_sales_flat via Data > Get Data (Power Query) and add PivotTables.",
    ], 1):
        notes.cell(row=i, column=1, value=line).font = BASE
    notes.column_dimensions["A"].width = 120
    wb.save(path)
    return path
